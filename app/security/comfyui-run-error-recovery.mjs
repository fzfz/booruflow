export const COMFYUI_RUN_RECOVERY_ACTIONS = Object.freeze({
  retryCurrent: 'retry_current',
  newTask: 'new_task',
  inspectRemote: 'inspect_remote',
  cleanup: 'cleanup',
  none: 'none'
});

const RETRY_CURRENT_CODES = new Set([
  'DATABASE_BUSY', 'INTERNAL_ERROR',
  'NODE_DEFINITION_MISSING', 'COMFYUI_INSTANCE_UNAVAILABLE',
  'COMFYUI_CONNECTION_FAILED', 'COMFYUI_CREDENTIAL_ERROR', 'COMFYUI_REQUEST_TIMEOUT', 'COMFYUI_REQUEST_CANCELED',
  'COMFYUI_HTTP_ERROR', 'COMFYUI_PROTOCOL_ERROR', 'COMFYUI_VERSION_UNAVAILABLE', 'COMFYUI_RUNTIME_UNAVAILABLE',
  'COMFYUI_REMOTE_MISSING', 'COMFYUI_REMOTE_ERROR', 'COMFYUI_RUN_FAILED',
  'RUNTIME_MEDIA_UPLOAD_UNAVAILABLE', 'RUNTIME_MEDIA_UPLOAD_MISMATCH'
]);

const NEW_TASK_CODES = new Set([
  'ITEM_UNAVAILABLE', 'RELATION_CONFLICT', 'NOT_FOUND',
  'PARAMETER_OPTION_UNAVAILABLE', 'PARAMETER_REQUIRED', 'PARAMETER_INVALID',
  'RUNTIME_MEDIA_NOT_FOUND', 'RUNTIME_MEDIA_INVALID',
  'COMFYUI_PROMPT_REJECTED', 'COMFYUI_OUTPUT_MISSING', 'COMFYUI_OUTPUT_LIMIT', 'COMFYUI_OUTPUT_INVALID', 'UPLOAD_TOO_LARGE',
  'OUTPUT_NODE_MISSING', 'INSTANCE_WORKFLOW_VERSION_UNSUPPORTED',
  'LINK_SOURCE_MISSING', 'LINK_MISSING', 'BYPASS_CYCLE', 'BYPASS_ROUTE_MISSING', 'BYPASS_LINK_MISSING', 'REQUIRED_INPUT_MISSING'
]);

export function comfyuiRunRecoveryAction(code) {
  if (RETRY_CURRENT_CODES.has(code)) return COMFYUI_RUN_RECOVERY_ACTIONS.retryCurrent;
  if (NEW_TASK_CODES.has(code)) return COMFYUI_RUN_RECOVERY_ACTIONS.newTask;
  if (code === 'COMFYUI_SUBMISSION_OUTCOME_UNKNOWN') return COMFYUI_RUN_RECOVERY_ACTIONS.inspectRemote;
  if (code === 'COMFYUI_OUTPUT_CLEANUP_FAILED') return COMFYUI_RUN_RECOVERY_ACTIONS.cleanup;
  return COMFYUI_RUN_RECOVERY_ACTIONS.none;
}

export function iterativeComfyuiRetryOperation(code) {
  return comfyuiRunRecoveryAction(code) === COMFYUI_RUN_RECOVERY_ACTIONS.retryCurrent ? 'retry_comfyui' : null;
}
